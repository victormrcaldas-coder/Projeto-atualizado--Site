/* ================================================================
   aplicação da curadoria
   ================================================================ */
let _curadoriaAplicada = { corrigidas: 0, autoria: 0, restantes: 0 };
function aplicarCuradoriaFinal() {
  const regras = CURADORIA_FINAL.map((r) => ({
    autor: bNorm(r[0]),
    frag: bNorm(r[1]),
    src: r[2],
    st: r[3],
    novoAutor: r[4] || null,
    usada: 0
  }));
  let corr = 0,
    autoria = 0;
  QUOTES.forEach((q) => {
    if (q.st !== 'R') return;
    const a = bNorm(canonAuthor(q.author));
    const t = bNorm(q.text);
    const regra = regras.find((r) => (a === r.autor || a.includes(r.autor) || r.autor.includes(a)) && t.includes(r.frag));
    if (!regra) return;
    regra.usada++;
    q.src = regra.src;
    q.st = regra.st;
    if (regra.novoAutor && canonAuthor(q.author) !== regra.novoAutor) {
      q.autorAnterior = q.author;
      q.author = regra.novoAutor;
      autoria++;
    }
    corr++;
  });
  _curadoriaAplicada = {
    corrigidas: corr,
    autoria,
    restantes: QUOTES.filter((q) => q.st === 'R').length
  };
  return _curadoriaAplicada;
}
